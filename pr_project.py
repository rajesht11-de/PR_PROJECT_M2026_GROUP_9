def extract_hog_features(images):

    features_list = []

    for image in images:

        features = hog(
            image,
            orientations=9,
            pixels_per_cell=(4, 4),
            cells_per_block=(2, 2),
            block_norm="L2-Hys",
            feature_vector=True
        )

        features_list.append(features)

    return np.asarray(features_list, dtype=np.float32)


