N_SPLITS = 3

cv = StratifiedKFold(
    n_splits=N_SPLITS,
    shuffle=True,
    random_state=SEED
)

cv_records = []

for name in build_models():

    print("\nRunning model:", name)

    X_current = X_for_method[name]

    for fold, (train_idx, val_idx) in enumerate(
        cv.split(X_dev, y_dev), start=1
    ):

        model = build_models()[name]

        X_train_fold = X_current[train_idx]

        X_val_fold = X_current[val_idx]

        y_train_fold = y_dev[train_idx]

        y_val_fold = y_dev[val_idx]

        start_time = time.time()

        model.fit(X_train_fold, y_train_fold)

        y_pred_fold = model.predict(X_val_fold)

        elapsed = time.time() - start_time

        accuracy = accuracy_score(
            y_val_fold,
            y_pred_fold
        )

        macro_f1 = f1_score(
            y_val_fold,
            y_pred_fold,
            average="macro"
        )

        macro_precision = precision_score(
            y_val_fold,
            y_pred_fold,
            average="macro",
            zero_division=0
        )

        macro_recall = recall_score(
            y_val_fold,
            y_pred_fold,
            average="macro",
            zero_division=0
        )

        cv_records.append({

            "Model": name,

            "Fold": fold,

            "Accuracy": accuracy,

            "Macro_F1": macro_f1,

            "Macro_Precision": macro_precision,

            "Macro_Recall": macro_recall,

            "Time_Seconds": elapsed

        })

        print(
            f"Fold {fold}: "
            f"Accuracy = {accuracy:.4f}, "
            f"Macro-F1 = {macro_f1:.4f}"
        )


cv_results = pd.DataFrame(cv_records)

